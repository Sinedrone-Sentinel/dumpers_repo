#!/usr/bin/env node
/**
 * Sync BP Dumper version to Python, Go embed pins, and package manifests.
 *
 * Usage:
 *   node scripts/sync-dumper-version.mjs           # read scripts/bp-dumper/version.json
 *   node scripts/sync-dumper-version.mjs 1.2.0     # set explicit version
 */
import { readFileSync, writeFileSync } from 'fs'
import { dirname, join } from 'path'
import { fileURLToPath } from 'url'
import { copyDumperVersionTargets } from './lib/blueprintNameLookup.mjs'

const __dirname = dirname(fileURLToPath(import.meta.url))
const ROOT = join(__dirname, '..')
const VERSION_FILE = join(ROOT, 'scripts', 'bp-dumper', 'version.json')
const PACKAGE_FILE = join(ROOT, 'scripts', 'bp-dumper', 'package.json')
const PY_VERSION = join(ROOT, 'scripts', 'bp-dumper-py', '_version.py')
const GO_VERSION = join(ROOT, 'scripts', 'bp-dumper-go', 'version.txt')
const APP_VERSION_FILE = join(ROOT, 'src', 'data', 'bp-dumper-version.json')

function readVersionFromFile() {
  const data = JSON.parse(readFileSync(VERSION_FILE, 'utf8'))
  if (typeof data.version !== 'string' || !/^\d+\.\d+\.\d+$/.test(data.version)) {
    throw new Error(`Invalid version in ${VERSION_FILE}`)
  }
  return data.version
}

const version = process.argv[2] ?? readVersionFromFile()
if (!/^\d+\.\d+\.\d+$/.test(version)) {
  console.error(`Invalid semver: ${version}`)
  process.exit(1)
}

writeFileSync(VERSION_FILE, `${JSON.stringify({ version }, null, 2)}\n`)

const pkg = JSON.parse(readFileSync(PACKAGE_FILE, 'utf8'))
pkg.version = version
writeFileSync(PACKAGE_FILE, `${JSON.stringify(pkg, null, 2)}\n`)

writeFileSync(
  PY_VERSION,
  `# Generated by scripts/sync-dumper-version.mjs — do not edit.\n__version__ = "${version}"\n`
)

writeFileSync(GO_VERSION, `${version}\n`)

writeFileSync(APP_VERSION_FILE, `${JSON.stringify({ version }, null, 2)}\n`)

copyDumperVersionTargets(ROOT)

console.log(`BP Dumper version synced to ${version}`)
